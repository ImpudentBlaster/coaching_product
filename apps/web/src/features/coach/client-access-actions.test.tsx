import '@testing-library/jest-dom/vitest';
import { cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { ClientAccessActions } from './client-access-actions';
import { apiRequest, type ClientRelationship } from '../../lib/api';
const { switchToClient } = vi.hoisted(() => ({ switchToClient: vi.fn() }));
vi.mock('../../lib/api', () => ({ apiRequest: vi.fn() }));
vi.mock('../auth/auth-context', () => ({ useAuth: () => ({ switchToClient }) }));
beforeEach(() => { HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); }; HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); }; });
afterEach(() => { cleanup(); vi.resetAllMocks(); });
const client: ClientRelationship = { id: 'relationship', clientId: 'client', coachId: 'coach', status: 'APPROVED', rejectionReason: null, createdAt: '2026-10-07', client: { id: 'client', email: 'client@example.test', displayName: 'Taylor', role: 'CLIENT', approvalStatus: 'APPROVED', businessName: null, createdAt: '2026-10-07' } };
it('requires confirmation before deletion and keeps a failed action available for retry', async () => {
  const onSaved = vi.fn().mockResolvedValue(undefined);
  render(<MemoryRouter><ClientAccessActions client={client} disabled={false} onEdit={vi.fn()} onSaved={onSaved} /></MemoryRouter>);
  fireEvent.click(screen.getByRole('button', { name: 'Actions for Taylor' }));
  expect(screen.getByRole('menuitem', { name: 'Reset password' })).toBeInTheDocument();
  expect(screen.getByRole('menuitem', { name: 'Resend registration mail' })).toBeInTheDocument();
  fireEvent.click(screen.getByRole('menuitem', { name: 'Delete client' }));
  expect(apiRequest).not.toHaveBeenCalled();
  vi.mocked(apiRequest).mockRejectedValueOnce(new Error('Unable to delete'));
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Delete client' }));
  await screen.findByText('Unable to delete');
  expect(onSaved).not.toHaveBeenCalled();
  vi.mocked(apiRequest).mockResolvedValue(undefined);
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Delete client' }));
  await screen.findByRole('button', { name: 'Actions for Taylor' });
  expect(apiRequest).toHaveBeenCalledWith('/coach/clients/client', { method: 'DELETE' });
});
it('confirms switching and exchanges the session only after confirmation', async () => {
  render(<MemoryRouter><ClientAccessActions client={client} disabled={false} onEdit={vi.fn()} onSaved={vi.fn()} /></MemoryRouter>);
  fireEvent.click(screen.getByRole('button', { name: 'Actions for Taylor' }));
  fireEvent.click(screen.getByRole('menuitem', { name: 'Switch to client' }));
  expect(switchToClient).not.toHaveBeenCalled();
  switchToClient.mockRejectedValueOnce(new Error('Unable to switch'));
  fireEvent.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Switch to client' }));
  await screen.findByText('Unable to switch');
  expect(switchToClient).toHaveBeenCalledWith('client');
});
